//! The settings the simulation reads (ticket #11 item 6): the gate's fixed-input flags plus the
//! few remaining sim-affecting fields, each at its `GourceSettings::setGourceDefaults` value.

#[derive(Clone, Debug)]
pub struct SimSettings {
    /// `-WxH` (camera aspect ratio).
    pub display_width: i32,
    pub display_height: i32,
    /// `-r`, the video frame rate that fixes the tick rate (`setFrameExporter`).
    pub output_framerate: i32,
    /// `-o` or `--debug-dump-state` was given: fixed tick rate instead of wall-clock `dt`.
    pub exporting: bool,
    pub stop_at_time: f32,
    pub stop_at_end: bool,
    pub stop_position: f32,
    pub stop_timestamp: i64,
    pub start_position: f32,
    /// `--start-position random`: `Sim::new` draws `start_position` from the run's PRNG.
    pub start_position_random: bool,
    pub days_per_second: f32,
    pub auto_skip_seconds: f32,
    pub no_time_travel: bool,
    pub loop_: bool,
    pub loop_delay_seconds: f32,
    pub file_idle_time: f32,
    pub file_idle_time_at_end: f32,
    pub user_idle_time: f32,
    pub time_scale: f32,
    pub max_files: i32,
    pub max_user_speed: f32,
    pub max_file_lag: f32,
    pub user_friction: f32,
    pub user_scale: f32,
    pub elasticity: f32,
    pub filename_time: f32,
    pub hash_seed: i32,
    pub camera_zoom_default: f32,
    pub camera_zoom_min: f32,
    pub camera_zoom_max: f32,
    pub padding: f32,
    pub crop_vertical: bool,
    pub crop_horizontal: bool,
    pub disable_auto_rotate: bool,
    pub track_users: bool,
    pub highlight_all_users: bool,
    pub highlight_users: Vec<String>,
    pub follow_users: Vec<String>,
    pub caption_file: String,
    pub caption_duration: f32,
    /// 1-based index of this `[gource]` section, and how many there are.
    pub section: i32,
    pub repo_count: i32,
    pub path: String,
}

